"""Loader for the bundled D3 reference tables (format v1).

The binary ``d3_reference.bin`` is generated by ``tools/generate_d3_data.py``
from pinned upstream sources. The same file is embedded into the native
library at build time; both loaders apply the same structural validation.
"""

import functools
import hashlib
import json
import struct
from dataclasses import dataclass
from importlib import resources
from typing import Any, Final

import numpy as np
import numpy.typing as npt

from vanderfast.errors import InputError

MAGIC: Final = b"VDFD3TBL"
FORMAT_VERSION: Final = 1
HEADER_BYTES: Final = 512
BYTE_ORDER_MARK: Final = 0x01020304
FLAG_RADII_D3_SCALED: Final = 1 << 0
FLAG_ATOMIC_UNITS: Final = 1 << 1
SECTION_ALIGN: Final = 64

DTYPE_U8: Final = 1
DTYPE_F64: Final = 2

SECTION_NREF: Final = 1
SECTION_REF_CN: Final = 2
SECTION_RCOV_D3: Final = 3
SECTION_R4R2: Final = 4
SECTION_C6: Final = 5
SECTION_RVDW: Final = 6

_SECTION_ORDER: Final = (
    SECTION_NREF,
    SECTION_REF_CN,
    SECTION_RCOV_D3,
    SECTION_R4R2,
    SECTION_C6,
    SECTION_RVDW,
)

_HEADER = struct.Struct("<8sIIIIIIIIQ")
_SECTION = struct.Struct("<IIQQ")

FloatArray = npt.NDArray[np.float64]
IntArray = npt.NDArray[np.int64]


class ReferenceDataError(InputError):
    """The reference table blob is malformed or does not match the manifest."""


def pair_index(zi: int, zj: int) -> int:
    """Return the zero-based packed index of an element pair (order-independent)."""
    if zi < zj:
        zi, zj = zj, zi
    return zi * (zi - 1) // 2 + (zj - 1)


@dataclass(frozen=True, eq=False)
class ReferenceTables:
    """Read-only views of the D3 reference tables in atomic units.

    Per-element arrays are indexed directly by atomic number; slot 0 is a
    sentinel. Reference coefficients are packed per element pair.
    """

    max_z: int
    max_ref: int
    nref: npt.NDArray[np.uint8]
    ref_offset: IntArray
    ref_cn_flat: FloatArray
    rcov: FloatArray
    r4r2: FloatArray
    c6_flat: FloatArray
    c6_offset: IntArray
    rvdw_flat: FloatArray
    source_id: str
    sha256: str

    def supports(self, z: int) -> bool:
        """Return whether atomic number ``z`` has reference data."""
        return 1 <= z <= self.max_z

    def _check(self, z: int) -> None:
        if not self.supports(z):
            msg = f"atomic number {z} is not supported (1..{self.max_z})"
            raise InputError(msg)

    def reference_cn(self, z: int) -> FloatArray:
        """Return the valid reference coordination numbers of element ``z``."""
        self._check(z)
        start = int(self.ref_offset[z])
        return self.ref_cn_flat[start : start + int(self.nref[z])]

    def c6_block(self, zi: int, zj: int) -> FloatArray:
        """Return reference C6 values with rows for ``zi`` and columns for ``zj``.

        This matches upstream ``get_c6(iref, jref, zi, zj)`` for every valid
        reference index pair.
        """
        self._check(zi)
        self._check(zj)
        big, small = (zi, zj) if zi >= zj else (zj, zi)
        ic = pair_index(big, small)
        start = int(self.c6_offset[ic])
        rows, cols = int(self.nref[big]), int(self.nref[small])
        block = self.c6_flat[start : start + rows * cols].reshape(rows, cols)
        return block if zi >= zj else block.T

    def vdw_radius(self, zi: int, zj: int) -> float:
        """Return the pairwise van der Waals radius in bohr."""
        self._check(zi)
        self._check(zj)
        return float(self.rvdw_flat[pair_index(zi, zj)])


def _section_dtype(code: int) -> np.dtype[Any]:
    if code == DTYPE_U8:
        return np.dtype(np.uint8)
    if code == DTYPE_F64:
        return np.dtype("<f8")
    msg = f"unknown section dtype {code}"
    raise ReferenceDataError(msg)


@dataclass(frozen=True)
class _Header:
    max_z: int
    max_ref: int
    n_refs: int
    n_pairs: int
    n_c6: int
    source_id: str


def _parse_header(blob: bytes) -> _Header:
    if len(blob) < HEADER_BYTES:
        msg = "reference data is shorter than its header"
        raise ReferenceDataError(msg)
    (magic, version, header_bytes, bom, flags, max_z, max_ref, n_refs, n_pairs, n_c6) = (
        _HEADER.unpack_from(blob, 0)
    )
    if magic != MAGIC:
        msg = "reference data has the wrong magic number"
        raise ReferenceDataError(msg)
    if version != FORMAT_VERSION or header_bytes != HEADER_BYTES or bom != BYTE_ORDER_MARK:
        msg = f"unsupported reference data format (version {version})"
        raise ReferenceDataError(msg)
    if flags != FLAG_RADII_D3_SCALED | FLAG_ATOMIC_UNITS:
        msg = f"unexpected reference data flags {flags:#x}"
        raise ReferenceDataError(msg)
    if n_pairs != max_z * (max_z + 1) // 2 or not 1 <= max_ref <= 8:  # noqa: PLR2004
        msg = "inconsistent reference data dimensions"
        raise ReferenceDataError(msg)
    n_sections, _ = struct.unpack_from("<II", blob, 112)
    if n_sections != len(_SECTION_ORDER):
        msg = f"expected {len(_SECTION_ORDER)} sections, found {n_sections}"
        raise ReferenceDataError(msg)
    source_id = blob[48:112].split(b"\0", 1)[0].decode("utf-8")
    return _Header(max_z, max_ref, n_refs, n_pairs, n_c6, source_id)


def _read_sections(data: bytes, header: _Header) -> dict[int, npt.NDArray[Any]]:
    expected_count = {
        SECTION_NREF: header.max_z + 1,
        SECTION_REF_CN: header.n_refs,
        SECTION_RCOV_D3: header.max_z + 1,
        SECTION_R4R2: header.max_z + 1,
        SECTION_C6: header.n_c6,
        SECTION_RVDW: header.n_pairs,
    }
    arrays: dict[int, npt.NDArray[Any]] = {}
    for index, expected_id in enumerate(_SECTION_ORDER):
        section_id, dtype_code, offset, count = _SECTION.unpack_from(
            data, 120 + index * _SECTION.size
        )
        if section_id != expected_id or count != expected_count[expected_id]:
            msg = f"section {index} is {section_id} with {count} entries"
            raise ReferenceDataError(msg)
        dtype = _section_dtype(dtype_code)
        if offset % SECTION_ALIGN or offset + count * dtype.itemsize > len(data):
            msg = f"section {section_id} is misaligned or out of bounds"
            raise ReferenceDataError(msg)
        arrays[section_id] = np.frombuffer(data, dtype=dtype, count=count, offset=offset)
    return arrays


def _offsets(header: _Header, nref: npt.NDArray[np.uint8]) -> tuple[IntArray, IntArray]:
    if nref[0] != 0 or np.any(nref[1:] < 1) or np.any(nref[1:] > header.max_ref):
        msg = "reference counts out of range"
        raise ReferenceDataError(msg)
    ref_offset = np.zeros(header.max_z + 2, dtype=np.int64)
    np.cumsum(nref, out=ref_offset[1:])
    if int(ref_offset[-1]) != header.n_refs:
        msg = "reference counts do not sum to the reference CN table length"
        raise ReferenceDataError(msg)
    sizes = np.empty(header.n_pairs, dtype=np.int64)
    for zi in range(1, header.max_z + 1):
        for zj in range(1, zi + 1):
            sizes[pair_index(zi, zj)] = int(nref[zi]) * int(nref[zj])
    c6_offset = np.zeros(header.n_pairs + 1, dtype=np.int64)
    np.cumsum(sizes, out=c6_offset[1:])
    if int(c6_offset[-1]) != header.n_c6:
        msg = "reference C6 table length does not match the reference counts"
        raise ReferenceDataError(msg)
    return ref_offset, c6_offset


def _frozen(array: npt.NDArray[Any]) -> npt.NDArray[Any]:
    view = array.view()
    view.flags.writeable = False
    return view


def parse_reference_tables(blob: bytes) -> ReferenceTables:
    """Validate and parse a format-v1 reference table blob.

    Args:
        blob: The complete file contents.

    Returns:
        Read-only table views backed by a private copy of ``blob``.

    Raises:
        ReferenceDataError: If any structural check fails.
    """
    header = _parse_header(blob)
    data = bytes(blob)
    arrays = _read_sections(data, header)
    nref = arrays[SECTION_NREF].astype(np.uint8)
    ref_offset, c6_offset = _offsets(header, nref)
    float_sections = (
        arrays[SECTION_REF_CN],
        arrays[SECTION_RCOV_D3][1:],
        arrays[SECTION_R4R2][1:],
        arrays[SECTION_C6],
        arrays[SECTION_RVDW],
    )
    if not all(np.all(np.isfinite(a)) for a in float_sections):
        msg = "reference data contains non-finite values"
        raise ReferenceDataError(msg)
    for array in (ref_offset, c6_offset, nref):
        array.flags.writeable = False
    return ReferenceTables(
        max_z=header.max_z,
        max_ref=header.max_ref,
        nref=nref,
        ref_offset=ref_offset,
        ref_cn_flat=_frozen(arrays[SECTION_REF_CN]),
        rcov=_frozen(arrays[SECTION_RCOV_D3]),
        r4r2=_frozen(arrays[SECTION_R4R2]),
        c6_flat=_frozen(arrays[SECTION_C6]),
        c6_offset=c6_offset,
        rvdw_flat=_frozen(arrays[SECTION_RVDW]),
        source_id=header.source_id,
        sha256=hashlib.sha256(data).hexdigest(),
    )


def _read_resource(name: str) -> bytes:
    return resources.files(__name__).joinpath(name).read_bytes()


@functools.cache
def load_manifest() -> dict[str, Any]:
    """Return the bundled provenance manifest."""
    manifest: dict[str, Any] = json.loads(_read_resource("manifest.json"))
    return manifest


@functools.cache
def load_methods() -> dict[str, Any]:
    """Return the bundled D3(BJ) method table."""
    methods: dict[str, Any] = json.loads(_read_resource("d3bj_methods.json"))
    expected = load_manifest()["outputs"]["d3bj_methods.json"]["sha256"]
    actual = hashlib.sha256(_read_resource("d3bj_methods.json")).hexdigest()
    if actual != expected:
        msg = "bundled method table does not match its manifest hash"
        raise ReferenceDataError(msg)
    return methods


@functools.cache
def load_reference_tables() -> ReferenceTables:
    """Return the bundled reference tables after verifying the manifest hash."""
    blob = _read_resource("d3_reference.bin")
    tables = parse_reference_tables(blob)
    expected = load_manifest()["outputs"]["d3_reference.bin"]["sha256"]
    if tables.sha256 != expected:
        msg = "bundled reference tables do not match their manifest hash"
        raise ReferenceDataError(msg)
    return tables


def read_reference_blob() -> bytes:
    """Return the raw bundled reference table bytes."""
    return _read_resource("d3_reference.bin")


