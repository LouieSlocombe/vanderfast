"""Loader for the bundled D4 reference tables (format v1).

The binary ``d4_reference.bin`` is generated by ``tools/generate_d4_data.py``
from pinned dftd4, multicharge, and mctc-lib sources. It stores the raw
upstream tables; reference polarizabilities and C6 coefficients are derived
from them for the requested charge-scaling parameters, as dftd4 does at model
construction. The same file is embedded into the native library at build time;
both loaders apply the same structural validation.
"""

import functools
import hashlib
import json
import math
import struct
from dataclasses import dataclass
from importlib import resources
from typing import Any, Final

import numpy as np
import numpy.typing as npt

from vanderfast.data import ReferenceDataError
from vanderfast.errors import InputError

MAGIC: Final = b"VDFD4TBL"
FORMAT_VERSION: Final = 1
HEADER_BYTES: Final = 512
BYTE_ORDER_MARK: Final = 0x01020304
FLAG_RCOV_SCALED: Final = 1 << 0
FLAG_ATOMIC_UNITS: Final = 1 << 1
FLAG_RAW_POLARIZABILITIES: Final = 1 << 2
FLAG_EEQ2019: Final = 1 << 3
FLAGS: Final = FLAG_RCOV_SCALED | FLAG_ATOMIC_UNITS | FLAG_RAW_POLARIZABILITIES | FLAG_EEQ2019
SECTION_ALIGN: Final = 64

DTYPE_U8: Final = 1
DTYPE_F64: Final = 2

SECTION_NREF: Final = 1
SECTION_NGW: Final = 2
SECTION_REFSYS: Final = 3
SECTION_REF_SCALARS: Final = 4
SECTION_ALPHAIW: Final = 5
SECTION_SECONDARY: Final = 6
SECTION_ELEMENT: Final = 7
SECTION_FREQ: Final = 8

_SECTION_ORDER: Final = (
    SECTION_NREF,
    SECTION_NGW,
    SECTION_REFSYS,
    SECTION_REF_SCALARS,
    SECTION_ALPHAIW,
    SECTION_SECONDARY,
    SECTION_ELEMENT,
    SECTION_FREQ,
)

REF_SCALAR_COLUMNS: Final = ("refcovcn", "refcn", "clsq", "clsh", "hcount", "ascale")
ELEMENT_COLUMNS: Final = (
    "zeff",
    "hardness",
    "en",
    "rcov_d4",
    "r4r2",
    "eeq_chi",
    "eeq_eta",
    "eeq_kcnchi",
    "eeq_rad",
    "eeq_rcov",
)
MAX_CN_BIN: Final = 19

_HEADER = struct.Struct("<8sIIIIIIIIQ")
_SECTION = struct.Struct("<IIQQ")

FloatArray = npt.NDArray[np.float64]
IntArray = npt.NDArray[np.int64]


def fortran_nint(value: float) -> int:
    """Fortran ``nint``: round half away from zero."""
    return int(math.copysign(math.floor(abs(value) + 0.5), value))


def gaussian_counts(refcn: npt.ArrayLike) -> list[int]:
    """Upstream ``set_refgw``: Gaussians per reference from the reference-CN histogram.

    The histogram starts with one count in bin 0, so references near CN 0 get
    more Gaussians than an isolated reference elsewhere.
    """
    values = [float(v) for v in np.asarray(refcn, dtype=np.float64)]
    cnc = [1] + [0] * MAX_CN_BIN
    for value in values:
        cnc[min(fortran_nint(value), MAX_CN_BIN)] += 1
    counts = []
    for value in values:
        icn = cnc[min(fortran_nint(value), MAX_CN_BIN)]
        counts.append(icn * (icn + 1) // 2)
    return counts


@dataclass(frozen=True, eq=False)
class D4ReferenceTables:
    """Read-only views of the D4 reference tables in atomic units.

    Per-element arrays are indexed directly by atomic number with slot 0 a NaN
    sentinel. References of element ``z`` occupy rows
    ``ref_offset[z]:ref_offset[z + 1]`` of the per-reference arrays. Secondary
    systems are indexed 1..17 (row 0 is a sentinel).
    """

    max_z: int
    max_ref: int
    nref: npt.NDArray[np.uint8]
    ref_offset: IntArray
    ngw: npt.NDArray[np.uint8]
    refsys: npt.NDArray[np.uint8]
    ref_scalars: FloatArray
    alphaiw: FloatArray
    sscale: FloatArray
    secaiw: FloatArray
    element: FloatArray
    freq: FloatArray
    weights: FloatArray
    source_id: str
    sha256: str

    @property
    def n_refs(self) -> int:
        """Total number of references of the supported elements."""
        return int(self.refsys.shape[0])

    def supports(self, z: int) -> bool:
        """Return whether atomic number ``z`` has reference data."""
        return 1 <= z <= self.max_z

    def _check(self, z: int) -> None:
        if not self.supports(z):
            msg = f"atomic number {z} is not supported by D4 (1..{self.max_z})"
            raise InputError(msg)

    def references(self, z: int) -> slice:
        """Return the rows of element ``z`` in the per-reference arrays."""
        self._check(z)
        return slice(int(self.ref_offset[z]), int(self.ref_offset[z + 1]))

    def reference_column(self, name: str) -> FloatArray:
        """Return one per-reference scalar column (see ``REF_SCALAR_COLUMNS``)."""
        column: FloatArray = self.ref_scalars[:, REF_SCALAR_COLUMNS.index(name)]
        return column

    def element_column(self, name: str) -> FloatArray:
        """Return one per-element column indexed by Z (see ``ELEMENT_COLUMNS``)."""
        column: FloatArray = self.element[:, ELEMENT_COLUMNS.index(name)]
        return column


def _section_dtype(code: int) -> np.dtype[Any]:
    if code == DTYPE_U8:
        return np.dtype(np.uint8)
    if code == DTYPE_F64:
        return np.dtype("<f8")
    msg = f"unknown section dtype {code}"
    raise ReferenceDataError(msg)


@dataclass(frozen=True)
class _Header:
    max_z: int
    max_ref: int
    n_refs: int
    n_freq: int
    n_secondary: int
    source_id: str


def _parse_header(blob: bytes) -> _Header:
    if len(blob) < HEADER_BYTES:
        msg = "D4 reference data is shorter than its header"
        raise ReferenceDataError(msg)
    (magic, version, header_bytes, bom, flags, max_z, max_ref, n_refs, n_freq, n_secondary) = (
        _HEADER.unpack_from(blob, 0)
    )
    if magic != MAGIC:
        msg = "D4 reference data has the wrong magic number"
        raise ReferenceDataError(msg)
    if version != FORMAT_VERSION or header_bytes != HEADER_BYTES or bom != BYTE_ORDER_MARK:
        msg = f"unsupported D4 reference data format (version {version})"
        raise ReferenceDataError(msg)
    if flags != FLAGS:
        msg = f"unexpected D4 reference data flags {flags:#x}"
        raise ReferenceDataError(msg)
    if not 1 <= max_ref <= 8 or n_freq < 2 or not 1 <= n_secondary <= 255:  # noqa: PLR2004
        msg = "inconsistent D4 reference data dimensions"
        raise ReferenceDataError(msg)
    n_sections, _ = struct.unpack_from("<II", blob, 112)
    if n_sections != len(_SECTION_ORDER):
        msg = f"expected {len(_SECTION_ORDER)} sections, found {n_sections}"
        raise ReferenceDataError(msg)
    source_id = blob[48:112].split(b"\0", 1)[0].decode("utf-8")
    return _Header(max_z, max_ref, n_refs, n_freq, n_secondary, source_id)


def _read_sections(data: bytes, header: _Header) -> dict[int, npt.NDArray[Any]]:
    expected_count = {
        SECTION_NREF: header.max_z + 1,
        SECTION_NGW: header.n_refs,
        SECTION_REFSYS: header.n_refs,
        SECTION_REF_SCALARS: header.n_refs * len(REF_SCALAR_COLUMNS),
        SECTION_ALPHAIW: header.n_refs * header.n_freq,
        SECTION_SECONDARY: (header.n_secondary + 1) * (header.n_freq + 1),
        SECTION_ELEMENT: (header.max_z + 1) * len(ELEMENT_COLUMNS),
        SECTION_FREQ: 2 * header.n_freq,
    }
    arrays: dict[int, npt.NDArray[Any]] = {}
    for index, expected_id in enumerate(_SECTION_ORDER):
        section_id, dtype_code, offset, count = _SECTION.unpack_from(
            data, 120 + index * _SECTION.size
        )
        if section_id != expected_id or count != expected_count[expected_id]:
            msg = f"section {index} is {section_id} with {count} entries"
            raise ReferenceDataError(msg)
        dtype = _section_dtype(dtype_code)
        if offset % SECTION_ALIGN or offset + count * dtype.itemsize > len(data):
            msg = f"section {section_id} is misaligned or out of bounds"
            raise ReferenceDataError(msg)
        arrays[section_id] = np.frombuffer(data, dtype=dtype, count=count, offset=offset)
    return arrays


def _ref_offsets(header: _Header, nref: npt.NDArray[np.uint8]) -> IntArray:
    if nref[0] != 0 or np.any(nref[1:] < 1) or np.any(nref[1:] > header.max_ref):
        msg = "D4 reference counts out of range"
        raise ReferenceDataError(msg)
    ref_offset = np.zeros(header.max_z + 2, dtype=np.int64)
    np.cumsum(nref, out=ref_offset[1:])
    if int(ref_offset[-1]) != header.n_refs:
        msg = "D4 reference counts do not sum to the reference table length"
        raise ReferenceDataError(msg)
    return ref_offset


def _validate_values(
    header: _Header, arrays: dict[int, npt.NDArray[Any]], ref_offset: IntArray
) -> None:
    finite = (
        arrays[SECTION_REF_SCALARS],
        arrays[SECTION_ALPHAIW],
        arrays[SECTION_SECONDARY][header.n_freq + 1 :],
        arrays[SECTION_ELEMENT][len(ELEMENT_COLUMNS) :],
        arrays[SECTION_FREQ],
    )
    if not all(np.all(np.isfinite(a)) for a in finite):
        msg = "D4 reference data contains non-finite values"
        raise ReferenceDataError(msg)
    if np.any(arrays[SECTION_REFSYS] > header.n_secondary):
        msg = "D4 reference data names an unknown secondary system"
        raise ReferenceDataError(msg)
    freq = arrays[SECTION_FREQ][: header.n_freq]
    if np.any(np.diff(freq) <= 0.0):
        msg = "D4 frequency grid is not increasing"
        raise ReferenceDataError(msg)
    refcn = arrays[SECTION_REF_SCALARS].reshape(header.n_refs, -1)[
        :, REF_SCALAR_COLUMNS.index("refcn")
    ]
    ngw = arrays[SECTION_NGW]
    for z in range(1, header.max_z + 1):
        rows = slice(int(ref_offset[z]), int(ref_offset[z + 1]))
        if gaussian_counts(refcn[rows]) != [int(v) for v in ngw[rows]]:
            msg = f"D4 Gaussian counts of Z={z} do not match the reference CNs"
            raise ReferenceDataError(msg)


def _frozen(array: npt.NDArray[Any]) -> npt.NDArray[Any]:
    view = array.view()
    view.flags.writeable = False
    return view


def parse_d4_reference_tables(blob: bytes) -> D4ReferenceTables:
    """Validate and parse a format-v1 D4 reference table blob.

    Args:
        blob: The complete file contents.

    Returns:
        Read-only table views backed by a private copy of ``blob``.

    Raises:
        ReferenceDataError: If any structural check fails.
    """
    header = _parse_header(blob)
    data = bytes(blob)
    arrays = _read_sections(data, header)
    nref = arrays[SECTION_NREF].astype(np.uint8)
    ref_offset = _ref_offsets(header, nref)
    _validate_values(header, arrays, ref_offset)
    secondary = arrays[SECTION_SECONDARY].reshape(header.n_secondary + 1, header.n_freq + 1)
    freq = arrays[SECTION_FREQ].reshape(2, header.n_freq)
    for array in (ref_offset, nref):
        array.flags.writeable = False
    return D4ReferenceTables(
        max_z=header.max_z,
        max_ref=header.max_ref,
        nref=nref,
        ref_offset=ref_offset,
        ngw=_frozen(arrays[SECTION_NGW]),
        refsys=_frozen(arrays[SECTION_REFSYS]),
        ref_scalars=_frozen(arrays[SECTION_REF_SCALARS].reshape(header.n_refs, -1)),
        alphaiw=_frozen(arrays[SECTION_ALPHAIW].reshape(header.n_refs, header.n_freq)),
        sscale=_frozen(secondary[:, 0]),
        secaiw=_frozen(secondary[:, 1:]),
        element=_frozen(arrays[SECTION_ELEMENT].reshape(header.max_z + 1, -1)),
        freq=_frozen(freq[0]),
        weights=_frozen(freq[1]),
        source_id=header.source_id,
        sha256=hashlib.sha256(data).hexdigest(),
    )


def _read_resource(name: str) -> bytes:
    return resources.files("vanderfast.data").joinpath(name).read_bytes()


@functools.cache
def load_d4_manifest() -> dict[str, Any]:
    """Return the bundled D4 provenance manifest."""
    manifest: dict[str, Any] = json.loads(_read_resource("d4_manifest.json"))
    return manifest


@functools.cache
def load_d4_methods() -> dict[str, Any]:
    """Return the bundled D4 method table."""
    raw = _read_resource("d4_methods.json")
    expected = load_d4_manifest()["outputs"]["d4_methods.json"]["sha256"]
    if hashlib.sha256(raw).hexdigest() != expected:
        msg = "bundled D4 method table does not match its manifest hash"
        raise ReferenceDataError(msg)
    methods: dict[str, Any] = json.loads(raw)
    return methods


@functools.cache
def load_d4_reference_tables() -> D4ReferenceTables:
    """Return the bundled D4 reference tables after verifying the manifest hash."""
    tables = parse_d4_reference_tables(_read_resource("d4_reference.bin"))
    expected = load_d4_manifest()["outputs"]["d4_reference.bin"]["sha256"]
    if tables.sha256 != expected:
        msg = "bundled D4 reference tables do not match their manifest hash"
        raise ReferenceDataError(msg)
    return tables


def read_d4_reference_blob() -> bytes:
    """Return the raw bundled D4 reference table bytes."""
    return _read_resource("d4_reference.bin")


